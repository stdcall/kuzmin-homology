class AbGroup:
    """Z_(n_1) x ... x Z_(n_l), elements are tuples."""

    def __init__(self, ords):
        self.ords = tuple(ords)
        self.elts = list(itertools.product(*[range(n) for n in ords]))
        self.index = {g: i for i, g in enumerate(self.elts)}
        self.one = tuple(0 for _ in ords)
        self.order = len(self.elts)
        self.name = ' x '.join('Z_%d' % n for n in ords)

    def mul(self, g, h):
        return tuple((a + b) % n for a, b, n in zip(g, h, self.ords))

    def inv(self, g):
        return tuple((-a) % n for a, n in zip(g, self.ords))

    def power(self, g, k):
        return tuple((a * k) % n for a, n in zip(g, self.ords))


def periodic_resolution(B):
    """Tensor product of the periodic resolutions of the cyclic factors:
    basis of F_a = tuples (a_1, .., a_l) with sum a; boundary(f) is a list
    of (f', {g: c}) meaning f -> sum f' (sum c g)."""
    l = len(B.ords)

    def theta(i, a):
        t = tuple(1 if j == i else 0 for j in range(l))
        if a % 2 == 1:
            return {t: 1, B.one: -1}
        return {B.power(t, k): 1 for k in range(B.ords[i])}

    def basis(a):
        return [f for f in itertools.product(range(a + 1), repeat=l)
                if sum(f) == a]

    def boundary(f):
        out = []
        sgn = 1
        for i in range(l):
            if f[i] > 0:
                f2 = tuple(f[j] - (1 if j == i else 0) for j in range(l))
                out.append((f2, {g: sgn * c for g, c in theta(i, f[i]).items()}))
            if f[i] % 2 == 1:
                sgn = -sgn
        return out
    return basis, boundary, sum


def ext_power(A, k):
    """Matrix of Lambda^k(A) on the basis e_I (I increasing, lexicographic),
    rows = images (row-vector convention)."""
    n = A.nrows()
    if k == 0:
        return identity_matrix(ZZ, 1)
    N = binomial(n, k)
    return matrix(ZZ, N, N, A.minors(k))


def ab_invariants(free, tors):
    return (free, sorted(e for e in tors if e != 1))


def ppart(tors, p):
    out = []
    for e in tors:
        q = 1
        while e % p == 0:
            e //= p
            q *= p
        if q > 1:
            out.append(q)
    return sorted(out)


def npart(tors, n):
    """Invariants of t_n: the p-primary parts for the primes p dividing n."""
    out = []
    for p, _ in (factor(n) if n > 1 else []):
        out += ppart(tors, p)
    return sorted(out)


def exponent(tors):
    e = 1
    for t in tors:
        e = e * t // gcd(e, t)
    return e


def chain_homology(mats, n, dim_n):
    """(free rank, torsion) of H_n of a complex of free abelian groups;
    mats[n]: C_n -> C_(n-1) with rows = C_n (None or absent if zero)."""
    Dn = mats.get(n)
    Dn1 = mats.get(n + 1)
    rk_n = Dn.rank() if Dn is not None and Dn.nrows() and Dn.ncols() else 0
    if Dn1 is not None and Dn1.nrows() and Dn1.ncols():
        ed = [e for e in Dn1.elementary_divisors() if e != 0]
    else:
        ed = []
    return ab_invariants(dim_n - rk_n - len(ed), ed)


def cochain_cohomology(mats, n, dim_n):
    """H^n of the dual complex: coboundary delta^(n-1) = mats[n]^T."""
    Dn = mats.get(n)        # delta^(n-1) = Dn^T: C^(n-1) -> C^n
    Dn1 = mats.get(n + 1)   # delta^n = Dn1^T
    rk_n1 = Dn1.rank() if Dn1 is not None and Dn1.nrows() and Dn1.ncols() else 0
    if Dn is not None and Dn.nrows() and Dn.ncols():
        ed = [e for e in Dn.transpose().elementary_divisors() if e != 0]
    else:
        ed = []
    return ab_invariants(dim_n - rk_n1 - len(ed), ed)


def group_chain_mats(B, act, mmax):
    """Boundary matrices of F (x)_B L, L a lattice with action act[g]."""
    basis, bound, _ = periodic_resolution(B)
    dim = next(iter(act.values())).nrows()
    mats = {}
    for m in range(1, mmax + 2):
        rows, cols = basis(m), basis(m - 1)
        ci = {c: i for i, c in enumerate(cols)}
        D = matrix(ZZ, len(rows) * dim, len(cols) * dim, sparse=True)
        for i, f in enumerate(rows):
            for f2, lam in bound(f):
                blk = matrix(ZZ, dim, dim)
                for g, c in lam.items():
                    blk += c * act[g]
                D.set_block(i * dim, ci[f2] * dim, blk)
        mats[m] = D
    dims = {m: len(basis(m)) * dim for m in range(mmax + 2)}
    return mats, dims


def group_homology(B, act, mmax):
    mats, dims = group_chain_mats(B, act, mmax)
    return {m: chain_homology(mats, m, dims[m]) for m in range(mmax + 1)}


def group_cohomology(B, act, mmax):
    """H^m(B, Hom(L, Z)) = cohomology of Hom(F (x)_B L, Z)."""
    mats, dims = group_chain_mats(B, act, mmax)
    return {m: cochain_cohomology(mats, m, dims[m]) for m in range(mmax + 1)}


def homology_mod(H, m, s):
    """Invariants of H_m(C (x) Z_s) from H_m(C), H_(m-1)(C) (universal
    coefficients)."""
    out = []
    free, tors = H[m]
    out += [s] * free + [gcd(e, s) for e in tors]
    if m >= 1:
        out += [gcd(e, s) for e in H[m - 1][1]]
    return sorted(e for e in out if e != 1)


def coinvariants(act):
    """(free rank, torsion) of L_B."""
    dim = next(iter(act.values())).nrows()
    rows = []
    for A in act.values():
        rows += (A - identity_matrix(ZZ, dim)).rows()
    R = matrix(ZZ, rows)
    ed = [e for e in R.elementary_divisors() if e != 0]
    return ab_invariants(dim - len(ed), ed)


def quotient_lattice(image_rows, ambient_act):
    """Z^N / span(image_rows) when the span is saturated: returns the
    action on the quotient, the projection matrix and the lift."""
    N = next(iter(ambient_act.values())).nrows()
    Im = matrix(ZZ, image_rows)
    S, P, Q = Im.smith_form()
    rho = Im.rank()
    check(all(S[i, i] == 1 for i in range(rho)),
          'quotient lattice: image saturated (elementary divisors 1)')
    proj = Q.matrix_from_columns(range(rho, N))
    lift = Q.inverse().matrix_from_rows(range(rho, N))
    act = {g: lift * A * proj for g, A in ambient_act.items()}
    return act, proj, lift


