def perm_sign(seq):
    """Sign of the permutation sorting seq (distinct entries)."""
    s = 1
    seq = list(seq)
    for i in range(len(seq)):
        for j in range(i + 1, len(seq)):
            if seq[i] > seq[j]:
                s = -s
    return s


def alternation_matrix(n, i, j):
    """alpha_(i j): Lambda^s(Z^n) -> Lambda^i (x) Lambda^j by the formula of
    p. 302 (sum over all permutations, divided by i! j!)."""
    s = i + j
    Ls = list(itertools.combinations(range(n), s))
    Li = {c: t for t, c in enumerate(itertools.combinations(range(n), i))}
    Lj = {c: t for t, c in enumerate(itertools.combinations(range(n), j))}
    A = matrix(ZZ, len(Ls), len(Li) * len(Lj))
    divisible = True
    for row, I in enumerate(Ls):
        acc = {}
        for w in itertools.permutations(range(s)):
            first = [I[w[t]] for t in range(i)]
            second = [I[w[t]] for t in range(i, s)]
            sg = perm_sign(w) * perm_sign(first) * perm_sign(second)
            col = Li[tuple(sorted(first))] * len(Lj) + Lj[tuple(sorted(second))]
            acc[col] = acc.get(col, 0) + sg
        for col, v in acc.items():
            divisible = divisible and v % (factorial(i) * factorial(j)) == 0
            A[row, col] = v // (factorial(i) * factorial(j))
    return A, divisible


def wedge_matrix(n, i, j):
    """beta_(i j): Lambda^i (x) Lambda^j -> Lambda^s, the natural map."""
    s = i + j
    Ls = {c: t for t, c in enumerate(itertools.combinations(range(n), s))}
    Li = list(itertools.combinations(range(n), i))
    Lj = list(itertools.combinations(range(n), j))
    Bm = matrix(ZZ, len(Li) * len(Lj), len(Ls))
    for a, I in enumerate(Li):
        for b, J in enumerate(Lj):
            if not set(I) & set(J):
                Bm[a * len(Lj) + b, Ls[tuple(sorted(I + J))]] = perm_sign(I + J)
    return Bm


def alpha_k_matrix(n, k):
    """alpha_k of § 1 as corrected (C527):
    m_1 ^ .. ^ m_k -> sum_(i=1)^k (-1)^(k-i) m_1 ^ .. ^ hat(m_i) ^ .. ^ m_k (x) m_i."""
    Lk = list(itertools.combinations(range(n), k))
    Lk1 = {c: t for t, c in enumerate(itertools.combinations(range(n), k - 1))}
    A = matrix(ZZ, len(Lk), len(Lk1) * n)
    for row, I in enumerate(Lk):
        for t in range(1, k + 1):
            rest = I[:t - 1] + I[t:]
            A[row, Lk1[rest] * n + I[t - 1]] += (-1) ** (k - t)
    return A


def wedge_coords(vectors, n):
    """Coordinates of v_1 ^ .. ^ v_q in Lambda^q(Z^n) (maximal minors)."""
    q = len(vectors)
    if q == 0:
        return [1]
    return list(matrix(ZZ, vectors).minors(q))


def alpha_k_on_vectors(vs, n):
    """Right-hand side of the formula for alpha_k on arbitrary vectors."""
    k = len(vs)
    N1 = binomial(n, k - 1)
    out = [0] * (N1 * n)
    for t in range(1, k + 1):
        w = wedge_coords(vs[:t - 1] + vs[t:], n)
        sg = (-1) ** (k - t)
        for a in range(N1):
            for b in range(n):
                out[a * n + b] += sg * w[a] * vs[t - 1][b]
    return out


def section_1_alternations():
    for n in range(2, 6):
        for k in range(2, n + 1):
            Ak = alpha_k_matrix(n, k)
            Aij, div = alternation_matrix(n, k - 1, 1)
            check(Ak == Aij, 'C527: alpha_k (sum i = 1..k, last factor m_k) = alpha_(k-1 1) of '
                  'p. 302, rank %d, k = %d' % (n, k))
            Bk = wedge_matrix(n, k - 1, 1)
            check(Ak * Bk == k * identity_matrix(ZZ, binomial(n, k)),
                  'p. 297: beta_k alpha_k = k on Lambda^k(Z^%d), k = %d' % (n, k))
            ok = True
            for _ in range(5):
                vs = [[random.randint(-3, 3) for _ in range(n)] for _ in range(k)]
                a, b = random.sample(range(k), 2)
                vs[b] = list(vs[a])
                ok = ok and all(x == 0 for x in alpha_k_on_vectors(vs, n))
                vs = [[random.randint(-3, 3) for _ in range(n)] for _ in range(k)]
                img = alpha_k_on_vectors(vs, n)
                lin = list(vector(ZZ, wedge_coords(vs, n)) * Ak)
                ok = ok and img == lin
            check(ok, 'p. 296: the right-hand side of alpha_k is alternating in m_1..m_k and '
                  'equals the linear map on m_1 ^ .. ^ m_k (rank %d, k = %d)' % (n, k))
        refuted((n - 1) - 1 == n - 1, 'C527: printed m_1 ^ .. ^ hat(m_i) ^ .. ^ m_(k-1) has '
                'k - 2 factors for i < k (k = %d), not k - 1' % n)
    for n in range(2, 6):
        for s in range(2, n + 1):
            for i in range(1, s):
                j = s - i
                A, div = alternation_matrix(n, i, j)
                check(div, 'p. 302: 1/(i! j!) sum sign(omega) ... is integral (n = %d, i = %d, '
                      'j = %d)' % (n, i, j))
                Bm = wedge_matrix(n, i, j)
                check(A * Bm == binomial(s, i) * identity_matrix(ZZ, binomial(n, s)),
                      'p. 302: beta_(i j) alpha_(i j) = s!/(i! j!) (n = %d, i = %d, j = %d)'
                      % (n, i, j))
                check(all(e == 1 for e in A.elementary_divisors() if e),
                      'p. 302: A^i o A^j = coker alpha_(i j) is torsion-free (n = %d, i = %d, '
                      'j = %d)' % (n, i, j))
    # C^i o C^j -> A^i o A^j injective for saturated C (A/C torsion-free)
    for c in (2, 3):
        for trial in range(3):
            Cb = matrix(ZZ, [[random.randint(-2, 2) for _ in range(4)]
                             for _ in range(4 - c)]).right_kernel_matrix()
            if Cb.nrows() != c:
                continue
            for (i, j) in [(1, 1), (2, 1), (1, 2)]:
                if i + j > c:
                    continue
                s = i + j
                AA, _ = alternation_matrix(4, i, j)
                AC, _ = alternation_matrix(c, i, j)
                Ei = matrix(ZZ, binomial(c, i), binomial(4, i), Cb.minors(i))
                Ej = matrix(ZZ, binomial(c, j), binomial(4, j), Cb.minors(j))
                Es = matrix(ZZ, binomial(c, s), binomial(4, s), Cb.minors(s))
                emb = Ei.tensor_product(Ej)
                V = ZZ ** (binomial(4, i) * binomial(4, j))
                CC = V.submodule(emb.rows())
                imA = V.submodule(AA.rows())
                imC = V.submodule((Es * AA).rows())
                check(CC.intersection(imA) == imC and V.submodule((AC * emb).rows()) == imC,
                      'p. 302: C^%d o C^%d -> A^%d o A^%d injective for a saturated C of rank %d '
                      'in Z^4' % (i, j, i, j, c))


