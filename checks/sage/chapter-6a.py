def order(tors):
    o = 1
    for t in tors:
        o *= t
    return o


def group_hc(B, act, mmax):
    """H_m(B, L) and H^m(B, Hom(L, Z)) for m <= mmax."""
    mats, dims = group_chain_mats(B, act, mmax)
    H = {m: chain_homology(mats, m, dims[m]) for m in range(mmax + 1)}
    Hc = {m: cochain_cohomology(mats, m, dims[m]) for m in range(mmax + 1)}
    return H, Hc


def wall_matrices(W, nmax):
    mats = {}
    dims = {n: len(W.gens(n)) for n in range(nmax + 2)}
    for n in range(1, nmax + 2):
        mats[n] = W.matrix(n) if dims[n] and dims[n - 1] else None
    return mats, dims


def j_map(E, W, n, mats, dims, coinv_tors):
    """Kernel and cokernel of j_n: Lambda^n(M) (x)_B Z -> H_n Phi from the
    column of W1 over the kernel M."""
    gens = W.gens(n)
    N = dims[n]
    Upos = [i for i, (f, S) in enumerate(gens) if W.fdeg(f) == 0]
    nonU = [i for i in range(N) if W.fdeg(gens[i][0]) > 0]
    Dn1 = mats[n + 1].dense_matrix()
    Dn = mats[n].dense_matrix()
    piB = Dn1.matrix_from_columns(nonU)
    rat_onto = N - Dn.rank() == piB.rank() + len(Upos)
    Cn = sorted(e for e in piB.elementary_divisors() if e not in (0, 1))
    if not coinv_tors:
        return [], Cn, rat_onto
    k = len(Upos)
    act = {g: ext_power(E.A[g], n) for g in E.B.elts}
    RB = matrix(ZZ, [row for g in E.B.elts
                     for row in (act[g] - identity_matrix(ZZ, k)).rows()])
    S, P, Q = RB.smith_form()
    divs = [S[i, i] for i in range(min(S.nrows(), S.ncols()))] + [0] * max(0, k - S.nrows())
    Qi = Q.inverse()
    tgens = [(Qi.row(i), divs[i]) for i in range(k) if divs[i] not in (0, 1)]
    Bmod = (ZZ ** N).submodule(Dn1.rows())
    kernel = []
    for cs in itertools.product(*[range(e) for _, e in tgens]):
        full = vector(ZZ, N)
        for c, (v, e) in zip(cs, tgens):
            for j, i in enumerate(Upos):
                full[i] += c * v[j]
        if full in Bmod:
            kernel.append(cs)
    # invariants of the kernel (a subgroup of prod Z_e): via a lattice quotient
    orders = [e for _, e in tgens]
    L = (ZZ ** len(orders)).submodule([vector(ZZ, cs) for cs in kernel]
                                      + [e * (ZZ ** len(orders)).gen(i)
                                         for i, e in enumerate(orders)])
    Kn = sorted(x for x in (L / L.submodule([e * (ZZ ** len(orders)).gen(i)
                                                for i, e in enumerate(orders)])).invariants()
                if x != 1)
    return Kn, Cn, rat_onto


def direct_Cn_upper(E, W, n, mats, dims):
    """C^n = coker(Res_n: H^n Phi -> Hom(Lambda^n M, Z)^B) from the cocycles
    of W1 (restriction to the column over M)."""
    gens = W.gens(n)
    Upos = [i for i, (f, S) in enumerate(gens) if W.fdeg(f) == 0]
    Z = mats[n + 1].dense_matrix().right_kernel_matrix() if mats.get(n + 1) is not None \
        else identity_matrix(ZZ, dims[n])
    res = Z.matrix_from_columns(Upos)
    k = len(Upos)
    stack = matrix(ZZ, [row for g in E.B.elts
                        for row in (ext_power(E.A[g], n) - identity_matrix(ZZ, k)).rows()])
    Inv = stack.right_kernel()
    sub = Inv.submodule(res.rows())
    return sorted(x for x in (Inv / sub).invariants() if x != 1), Inv.rank() - sub.rank()


def wang_cyclic(N, r, nmax):
    """Phi = A x| <x>, A = (ZZ Z_N)^(r-1): (rank H_n, C_n invariants)."""
    pts = [(j, b) for j in range(r - 1) for b in range(N)]
    orbit_data = {}
    for k in range(0, len(pts) + 1):
        seen = set()
        stabs = []
        signs_ok = True
        for S in itertools.combinations(range(len(pts)), k):
            if S in seen:
                continue
            orb = set()
            st = 0
            for t in range(N):
                img = [pts.index((pts[p][0], (pts[p][1] + t) % N)) for p in S]
                key = tuple(sorted(img))
                orb.add(key)
                if key == S:
                    st += 1
                    signs_ok = signs_ok and perm_sign(img) == 1
            seen |= orb
            stabs.append(st)
        orbit_data[k] = (len(stabs), stabs, signs_ok)
    out = {}
    for n in range(1, nmax + 1):
        a = orbit_data.get(n, (0, [], True))
        b = orbit_data.get(n - 1, (0, [], True))
        out[n] = (a[0] + b[0], sorted(s for s in b[1] if s > 1), a[2] and b[2])
    return out


def extension_case(ords, images, kmax, mmax, nW1, nW1_dual):
    E = FreeAbelianExtension(ords, images)
    B, name, d, r = E.B, E.name, E.d, E.r
    primes = [p for p, _ in factor(B.order)]
    check(d == B.order * (r - 1) + 1,
          'M = Ker sigma has rank |B|(r - 1) + 1 = %d (%s)' % (d, name))
    check(all(E.A[g] * E.A[h] == E.A[B.mul(g, h)] for g in B.elts for h in B.elts),
          'B acts on M by right multiplication (%s)' % name)
    # E^2 terms, coinvariants, cohomology of B with coefficients Lambda_k(M)
    E2, Hc, coinv = {}, {}, {}
    res_rank = len(periodic_resolution(B)[0](mmax + 1))
    for k in range(0, d + 1):
        act = {g: ext_power(E.A[g], k) for g in B.elts}
        coinv[k] = coinvariants(act)
        mm = mmax if k <= kmax and binomial(d, k) * res_rank <= 1600 else 2
        E2[k], Hc[k] = group_hc(B, act, mm)
        check(E2[k][0] == coinv[k], 'H_0(B, Lambda^%d M) = coinvariants (%s)' % (k, name))
    for k in range(0, d + 1):
        for m in E2[k]:
            free, tors = E2[k][m]
            if m > 0:
                check(free == 0 and B.order % exponent(tors) == 0,
                      'exc:odd-order-exponents: exponent of H_%d(B, M^%d) divides |B| (%s)'
                      % (m, k, name))
            else:
                check(B.order % exponent(tors) == 0,
                      'exc:odd-order-exponents: exponent of t(M^%d (x)_B Z) divides |B| (%s)'
                      % (k, name))
            if k >= 2:
                check(all((k * (k - 1)) % p == 0 for p in set(q for t in tors for q, _ in factor(t))),
                      'th:free-abelian-spectral-sequence (i): E^2_(%d %d) = t_k (+) t_(k-1) (%s)'
                      % (m, k, name))
                check((k * (k - 1)) % exponent(tors) == 0,
                      'lem:exterior-homology-exponent: exponent of E^2_(%d %d) divides k(k - 1) (%s)'
                      % (m, k, name))
            for p in primes:
                if k >= 2 and k % p not in (0, 1):
                    check(ppart(tors, p) == [], 'lem:exterior-power-relations-flat, '
                          'th:local-spectral-sequence (i): t_%d E^2_(%d %d) = 0 (%s)'
                          % (p, m, k, name))
                if k % p == 0 and m >= 2 and k + 1 <= d and m - 2 in E2[k + 1]:
                    check(ppart(tors, p) == ppart(E2[k + 1][m - 2][1], p),
                          'th:local-spectral-sequence (ii): t_%d E^2_(%d %d) = t_%d E^2_(%d %d) '
                          '(%s)' % (p, m, k, p, m - 2, k + 1, name))
    # Phi: W2 (all degrees)
    W2 = WallResolution(DerivedExtension(E))
    check(homotopy_identity(W2, 30), 'Wall resolution W2: d h + h d = 1 - eta eps (%s)' % name)
    mats2, dims2 = wall_matrices(W2, d + 1)
    check(all(W2.DD_zero(n) for n in range(2, min(d, 6) + 1)),
          'Wall resolution W2: D D = 0 on generators, n <= %d (%s)' % (min(d, 6), name))
    H = {n: chain_homology(mats2, n, dims2[n]) for n in range(d + 2)}
    Hup = {n: cochain_cohomology(mats2, n, dims2[n]) for n in range(d + 2)}
    check(H[0] == (1, []) and H[1] == (r, []),
          'exc:rational-first-homology: H_0 Phi = Z, H_1 Phi = Z^%d (%s)' % (r, name))
    check(H[d + 1] == (0, []) and sum((-1) ** n * H[n][0] for n in range(d + 1)) == 0,
          'H_n Phi = 0 above rank M = %d, Euler characteristic 0 (%s)' % (d, name))
    printed_fail = []
    for n in range(2, d + 1):
        Tn = H[n][1]
        check(H[n][0] == coinv[n][0], 'th:rational-homology-exterior: rank H_%d Phi = rank '
              'Lambda^%d M (x)_B Z = %d (%s)' % (n, n, coinv[n][0], name))
        check(Tn == npart(coinv[n][1], n),
              'th:free-abelian-extension-homology, lem:torsion-in-image: T_%d = '
              't_%d(Lambda^%d M (x)_B Z) = %s (%s)' % (n, n, n, Tn, name))
        check(n % exponent(Tn) == 0 and B.order % exponent(Tn) == 0,
              'exc:odd-order-exponents: exponent of T_%d divides (|B|, n) (%s)' % (n, name))
        if len(primes) == 1:
            p = primes[0]
            if n % p:
                check(Tn == [], 'exc:p-group-homology (i): H_%d Phi free (%s)' % (n, name))
            else:
                check(gcd(B.order, n) % exponent(Tn) == 0 and H[n] == coinv[n],
                      'exc:p-group-homology (ii): H_%d Phi = M^%d (x)_B Z (%s)' % (n, n, name))
        # cohomology: K^n = t(H^n Phi) (Res_n has a torsion-free target of the same rank)
        Kup = Hup[n][1]
        check(Hup[n][0] == coinv[n][0] and (n - 1) % exponent(Kup) == 0,
              'cor:cohomology-torsion-restriction: rank H^%d Phi = rank Hom(Lambda^%d M, Z)^B, '
              'exponent of K^%d divides n - 1 (%s)' % (n, n, n, name))
        check(Kup == npart(Hc[n - 1][1][1], n - 1),
              'th:free-abelian-extension-cohomology (corrected): K^%d = '
              't_%d H^1(B, Lambda_%d(M)) = %s (%s)' % (n, n - 1, n - 1, Kup, name))
        if Kup != npart(Hc[n][1][1], n - 1):
            printed_fail.append(n)
    # Phi: W1 (column over M gives j_n)
    if nW1:
        W1 = WallResolution(E)
        check(homotopy_identity(W1, 30), 'Wall resolution W1: d h + h d = 1 - eta eps (%s)' % name)
        mats1, dims1 = wall_matrices(W1, nW1 + 1)
        check(all(W1.DD_zero(n) for n in range(2, nW1 + 2)),
              'Wall resolution W1: D D = 0 on generators, n <= %d (%s)' % (nW1 + 1, name))
        for n in range(0, nW1 + 1):
            check(chain_homology(mats1, n, dims1[n]) == H[n],
                  'H_%d Phi from W1 = from W2 = %s (%s)' % (n, H[n], name))
        for n in range(2, nW1 + 1):
            Kn, Cn, onto = j_map(E, W1, n, mats1, dims1, coinv[n][1])
            check(onto, 'th:rational-homology-exterior: j_%d is rationally onto (%s)' % (n, name))
            check(Kn == npart(E2[n - 1][2][1], n - 1) == npart(coinv[n][1], n - 1),
                  'th:free-abelian-extension-homology: K_%d = t_%d H_2(B, Lambda^%d M) = '
                  't_%d(Lambda^%d M (x)_B Z) = %s (%s)' % (n, n - 1, n - 1, n - 1, n, Kn, name))
            check(Cn == npart(E2[n - 1][1][1], n - 1),
                  'th:free-abelian-extension-homology: C_%d = t_%d H_1(B, Lambda^%d M) = %s (%s)'
                  % (n, n - 1, n - 1, Cn, name))
            check((n - 1) % exponent(Kn) == 0 and (n - 1) % exponent(Cn) == 0,
                  'th:free-abelian-extension-homology: exponents of K_%d, C_%d divide n - 1 (%s)'
                  % (n, n, name))
            check(order(coinv[n][1]) == order(Kn) * order(H[n][1]),
                  'lem:torsion-in-image: t(H_%d Phi) lies in the image of j_%d (%s)' % (n, n, name))
            check(Cn == npart(Hc[n - 1][2][1], n - 1),
                  'th:free-abelian-extension-cohomology (corrected): t_%d H^2(B, Lambda_%d(M)) '
                  '= C_%d (%s)' % (n - 1, n - 1, n, name))
            if n <= nW1_dual:
                Cup, fr = direct_Cn_upper(E, W1, n, mats1, dims1)
                check(fr == 0 and Cup == Cn, 'cor:cohomology-torsion-restriction: C^%d = '
                      'coker Res_%d = %s = C_%d (%s)' % (n, n, Cup, n, name))
        if len(B.ords) == 1:
            wang = wang_cyclic(B.order, r, min(d, nW1))
            for n in range(1, min(d, nW1) + 1):
                rk, Cw, signs = wang[n]
                Kn, Cn, _ = (j_map(E, W1, n, mats1, dims1, coinv[n][1]) if n >= 1
                             else ([], [], True))
                check(signs and H[n] == (rk, []) and Kn == [] and Cn == Cw,
                      'Phi = A x| <x>: H_%d Phi = Z^%d (Wang sequence), K_%d = 0, C_%d = %s '
                      '(norm map; %s)' % (n, rk, n, n, Cw, name))
            wang = wang_cyclic(B.order, r, d)
            check(all(H[n] == (wang[n][0], []) for n in range(1, d + 1)),
                  'Phi = A x| <x>: H_n Phi for all n <= %d agrees with W2 (%s)' % (d, name))
    return E, E2, H, Hup, Hc, printed_fail


def section_2_extensions():
    cases = [((3,), [(1,), (0,)], 4, 4, 4, 4),
             ((3,), [(1,), (1,)], 4, 4, 4, 4),
             ((3,), [(1,), (0,), (0,)], 7, 4, 4, 4),
             ((5,), [(1,), (0,)], 6, 4, 6, 6),
             ((5,), [(1,), (0,), (0,)], 11, 6, 0, 0),
             ((9,), [(1,), (0,)], 10, 4, 4, 3),
             ((3, 3), [(1, 0), (0, 1)], 7, 4, 4, 3)]
    results = {}
    for c in cases:
        res = extension_case(*c)
        results[res[0].name + str(c[1])] = res
        printed_fail = res[5]
        if c[0] == (3, 3):
            check(4 in printed_fail and 7 in printed_fail,
                  'th:free-abelian-extension-cohomology: K^4 = Z_3, K^7 = Z_3 for Z_3 x Z_3')
            refuted(not printed_fail, 'th:free-abelian-extension-cohomology as printed: '
                    'K^n = t_(n-1) H^1(B, Lambda_n(M)) fails for n = %s (Z_3 x Z_3)' % printed_fail)
            Hup = res[3]
            refuted(Hup[4][1] == [], 'C561: printed theorem 4.4 "K^n = C^n = 0 for n != 1 mod p" '
                    'with p = 5 (B = Z_3 x Z_3 has no 5-torsion), n = 4: K^4 = t(H^4 Phi) = %s'
                    % Hup[4][1])
            check(npart(Hup[4][1], 5) == [], 'C561: t_5 K^4 = 0 for B = Z_3 x Z_3')
        if c[0] == (5,) and len(c[1]) == 3:
            E2 = res[1]
            check(all(E2[k][m] == (0, []) for k in E2 for m in E2[k]
                      if m > 0 and k % 5 not in (0, 1)) and
                  any(E2[k][m][1] for k in E2 for m in E2[k] if m > 0 and k % 5 == 0 and k),
                  'fig:local-e2-e3: for m > 0 only the rows k = 0, 1 mod 5 are non-zero '
                  '(Z_5, r = 3, k <= 11, m <= 6)')
    # hypothesis "B без p-кручения" of th:polynomial-homology / -cohomology
    E, E2, H, Hup, Hc, _ = results['Z_3, r = 2' + str([(1,), (0,)])]
    triv = {g: identity_matrix(ZZ, 1) for g in E.B.elts}
    HB = group_homology(E.B, triv, 8)

    def dim_mod3_homology(m):     # dim H_m(B, Z_3) by universal coefficients
        return HB[m][0] + len(ppart(HB[m][1], 3)) + (len(ppart(HB[m - 1][1], 3)) if m else 0)
    d5, d6 = dim_mod3_homology(5), dim_mod3_homology(6)
    check(d5 == 1 and d6 == 1, 'H_5(Z_3, Z_3) = H_6(Z_3, Z_3) = Z_3')
    # f_3^(3) = x^2: t_3 K_4 = f_3 H_5 = H_7, t_3 C_4 = H_6, t_3 K^4 = f_3 H^3 = H^5
    refuted(Hup[4][1] == [3] * d5, 'th:polynomial-cohomology without "B без p-кручения": '
            't_3 K^4 = %s for B = Z_3 (r = 2), f_3^(3) H^3(B, Z_3) = H^5(B, Z_3) = Z_3'
            % Hup[4][1])
    check(H[3][1] == [] and Hup[4][1] == [],
          'B = Z_3 (r = 2): H_3 Phi and H^4 Phi are torsion-free, so t_3 K^4 = 0')
    d7 = dim_mod3_homology(7)
    check(d7 == 1 and npart(E2[3][2][1], 3) == [],
          'B = Z_3 (r = 2): t_3 K_4 = t_3 H_2(B, Lambda^3 M) = 0, H_7(B, Z_3) = Z_3')
    refuted(npart(E2[3][2][1], 3) == [3] * d7, 'th:polynomial-homology without its hypothesis: '
            't_3 K_4 = f_3^(3) H_5(B, Z_3) = H_7(B, Z_3) for B = Z_3 (r = 2)')


