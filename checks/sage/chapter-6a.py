def lambda_map(Mx, j):
    """Lambda^j of a (possibly non-square) matrix: j x j minors."""
    if j == 0:
        return identity_matrix(ZZ, 1)
    return matrix(ZZ, binomial(Mx.nrows(), j), binomial(Mx.ncols(), j), Mx.minors(j))


def kron_vec(v, w):
    return vector(ZZ, [a * b for a in v for b in w])


def kron_act(a1, a2):
    return {g: a1[g].tensor_product(a2[g]) for g in a1}


def section_3_tor_circle():
    groups = [(2,), (3,), (4,), (2, 2), (5,), (2, 3)]
    c545_cases = []
    for ords in groups:
        B = AbGroup(ords)
        n = B.order
        nonid = [g for g in B.elts if g != B.one]
        idx = {g: i for i, g in enumerate(nonid)}
        actR = {h: matrix(ZZ, n, n, lambda a, b: 1 if B.index[B.mul(B.elts[a], h)] == b else 0)
                for h in B.elts}
        actD = {}
        for h in B.elts:
            A = matrix(ZZ, n - 1, n - 1)
            for g in nonid:
                gh = B.mul(g, h)
                if gh != B.one:
                    A[idx[g], idx[gh]] += 1
                if h != B.one:
                    A[idx[g], idx[h]] -= 1
            actD[h] = A
        inc = matrix(ZZ, n - 1, n)
        for g in nonid:
            inc[idx[g], B.index[g]] = 1
            inc[idx[g], B.index[B.one]] = -1
        check(all(actD[h] * inc == inc * actR[h] for h in B.elts),
              'Delta -> ZZ B is a module map (%s)' % B.name)
        trivial = {h: identity_matrix(ZZ, 1) for h in B.elts}
        for s in ((2, 3, 4) if n <= 4 else (2, 3)):
            if s > n - 1:
                continue

            def circle(act1, rank1):
                """X^(s-1) o X = coker(alpha: Lambda^s X -> Lambda^(s-1) X (x) X)."""
                amb = kron_act({h: ext_power(act1[h], s - 1) for h in B.elts}, act1)
                return quotient_lattice(alpha_k_matrix(rank1, s).rows(), amb)
            QD, projD, liftD = circle(actD, n - 1)
            QR, projR, liftR = circle(actR, n)
            Is = lambda_map(inc, s - 1).tensor_product(inc)
            mapDR = liftD * Is * projR
            check(mapDR.rank() == mapDR.nrows(),
                  'p. 309: Delta^%d o Delta -> R^%d o R is injective (%s)' % (s - 1, s - 1, B.name))
            L, projL, liftL = quotient_lattice(mapDR.rows(), QR)
            rkL = next(iter(L.values())).nrows()
            check(rkL == binomial(n - 1, s - 2) * (n - 1) + binomial(n - 1, s - 2),
                  'p. 310: L_%d is torsion-free of rank rank(Delta^%d (x) Delta) + rank '
                  'Delta^%d (%s)' % (s, s - 2, s - 2, B.name))
            # f: Delta^(s-2) (x) R -> L_s, a (x) g -> class of (a ^ g) (x) g
            wedge = wedge_matrix(n, s - 2, 1)
            Ls2 = lambda_map(inc, s - 2)
            rowsf = []
            for a in range(binomial(n - 1, s - 2)):
                for g in B.elts:
                    eg = vector(ZZ, n)
                    eg[B.index[g]] = 1
                    ag = kron_vec(Ls2.row(a), eg) * wedge
                    rowsf.append(kron_vec(ag, eg) * projR * projL)
            fm = matrix(ZZ, rowsf)
            src = kron_act({h: ext_power(actD[h], s - 2) for h in B.elts}, actR)
            check(all(src[h] * fm == fm * L[h] for h in B.elts),
                  'p. 311: f: Delta^%d (x) R -> L_%d is a module map (%s)' % (s - 2, s, B.name))
            ed = fm.elementary_divisors()
            check(fm.nrows() == fm.ncols() and 0 not in ed and
                  sorted(e for e in ed if e != 1) == [s] * binomial(n - 1, s - 1),
                  'p. 311-312: f is a monomorphism and N_%d = coker f has the invariants of '
                  'Delta^%d (x) Z_%d (%s)' % (s, s - 1, s, B.name))
            one_class = fm.row(0)
            check(one_class != 0, 'C549: f(r ^ 1 (x) 1) has infinite order in L_%d, so the printed '
                  '"+" differs from f(r (x) (b - 1)) by 2 f(r (x) 1) != 0 (%s)' % (s, B.name))
            LambdaR = {h: ext_power(actR[h], s) for h in B.elts}
            LambdaD1 = {h: ext_power(actD[h], s - 1) for h in B.elts}
            for Dname, Dact in (('Z', trivial), ('Delta', actD)):
                size = next(iter(Dact.values())).nrows() * max(
                    next(iter(QD.values())).nrows(), next(iter(QR.values())).nrows())
                mm = 4 if size <= 120 else (3 if size <= 300 else 2)
                if size > 600:
                    continue
                Hc = group_homology(B, kron_act(Dact, QD), mm)
                check(all(Hc[m][0] == 0 and (s * s) % exponent(Hc[m][1]) == 0
                          for m in range(1, mm + 1)),
                      'lem:tor-circle-product: s^2 Tor_m(%s, Delta^%d o Delta) = 0, m = 1..%d, '
                      's = %d (%s)' % (Dname, s - 1, mm, s, B.name))
                refuted(Hc[0][0] == 0 and (s * s) % exponent(Hc[0][1]) == 0,
                        'lem:tor-circle-product at m = 0 (printed without m > 0): Tor_0 has rank '
                        '%d (%s, D = %s, s = %d)' % (Hc[0][0], B.name, Dname, s))
                Hr = group_homology(B, kron_act(Dact, QR), mm)
                check(all(Hr[m][0] == 0 and s % exponent(Hr[m][1]) == 0
                          for m in range(1, mm + 1)),
                      'p. 309 (i): s Tor_m(%s, R^%d o R) = 0, m = 1..%d, s = %d (%s)'
                      % (Dname, s - 1, mm, s, B.name))
                if Dname == 'Z':
                    Hl = group_homology(B, LambdaR, mm)
                    check(all(Hr[m] == Hl[m - 1] for m in range(2, mm + 1)),
                          'C545: Tor_m(Z, R^%d o R) = Tor_(m-1)(Z, R^%d), m = 2..%d (%s)'
                          % (s - 1, s, mm, B.name))
                    if any(Hr[m] != Hl[m] for m in range(2, mm + 1)):
                        c545_cases.append((B.name, s))
                HL = group_homology(B, kron_act(Dact, L), mm)
                HD = group_homology(B, kron_act(Dact, LambdaD1), mm)
                check(all(HL[m][0] == 0 and HL[m][1] == homology_mod(HD, m, s)
                          for m in range(1, mm + 1)),
                      'p. 310 (ii): Tor_m(%s, L_%d) = Tor_m(%s, Delta^%d (x) Z_%d), m = 1..%d (%s)'
                      % (Dname, s, Dname, s - 1, s, mm, B.name))
    refuted(not c545_cases, 'C545 printed Tor_m(Z, R^(s-1) o R) = Tor_m(Z, R^s) fails for %s'
            % c545_cases)


