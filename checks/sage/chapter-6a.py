class TGroup:
    def __init__(self, src, name):
        G = libgap.eval(src)
        if not G.IsPermGroup():
            G = G.IsomorphismPermGroup().Image()
        deg = max(1, int(G.LargestMovedPoint()))
        els = list(G.AsSSortedList())
        perms = [tuple(int(v) - 1 for v in libgap.ListPerm(x, deg)) for x in els]
        index = {p: i for i, p in enumerate(perms)}
        self.N = len(els)
        self.name = name
        self.mul = [[index[tuple(q[p[t]] for t in range(deg))] for q in perms]
                    for p in perms]
        self.e = index[tuple(range(deg))]
        self.gens = [index[tuple(int(v) - 1 for v in libgap.ListPerm(x, deg))]
                     for x in G.GeneratorsOfGroup()]
        self.has_involution = any(self.mul[g][g] == self.e and g != self.e
                                  for g in range(self.N))


def subset_action(T, r, S, g):
    """Right action of g on the basis vector e_S of Lambda^k((ZZ B)^r);
    points are (i, b) coded i * N + b.  Returns (sign, image)."""
    img = [(p // T.N) * T.N + T.mul[p % T.N][g] for p in S]
    return perm_sign(img), tuple(sorted(img))


def section_2_induced():
    groups = [('CyclicGroup(IsPermGroup, 2)', 'Z_2'), ('CyclicGroup(IsPermGroup, 3)', 'Z_3'),
              ('CyclicGroup(IsPermGroup, 4)', 'Z_4'),
              ('DirectProduct(CyclicGroup(IsPermGroup, 2), CyclicGroup(IsPermGroup, 2))', 'Z_2^2'),
              ('CyclicGroup(IsPermGroup, 5)', 'Z_5'), ('SymmetricGroup(3)', 'S_3'),
              ('CyclicGroup(IsPermGroup, 6)', 'Z_6'), ('DihedralGroup(IsPermGroup, 8)', 'D_8'),
              ('QuaternionGroup(IsPermGroup, 8)', 'Q_8'), ('AlternatingGroup(4)', 'A_4')]
    for src, name in groups:
        T = TGroup(src, name)
        for r in ((1, 2) if T.N <= 4 else (1,)):
            pts = r * T.N
            for k in range(1, pts + 1):
                if binomial(pts, k) > 1000:
                    continue
                seen = set()
                ok_div = ok_tensor = ok_sign = True
                n_free = n_two = 0
                for S in itertools.combinations(range(pts), k):
                    if S in seen:
                        continue
                    orbit = set()
                    stab = []
                    for g in range(T.N):
                        sg, img = subset_action(T, r, S, g)
                        orbit.add(img)
                        if img == S:
                            stab.append((g, sg))
                    seen |= orbit
                    C = len(stab)
                    ok_div = ok_div and k % C == 0 and len(orbit) * C == T.N
                    sizes = [sum(1 for p in S if p // T.N == i) for i in range(r)]
                    ok_tensor = ok_tensor and all(ki % C == 0 for ki in sizes if ki)
                    nontriv = any(sg == -1 for g, sg in stab)
                    ok_sign = ok_sign and (not nontriv or (C % 2 == 0 and k % 2 == 0))
                    if nontriv:
                        n_two += 1
                    else:
                        n_free += 1
                check(ok_div and ok_tensor, 'prop:exterior-power-induced: Lambda^%d((ZZ %s)^%d): '
                      'stabilisers have order dividing every k_i' % (k, name, r))
                check(ok_sign, 'cor:exterior-power-coinvariants: a non-trivial sign needs |C| '
                      'and k even (%s, r = %d, k = %d)' % (name, r, k))
                if binomial(pts, k) <= 400:
                    basis = list(itertools.combinations(range(pts), k))
                    bi = {S: t for t, S in enumerate(basis)}
                    rows = []
                    for g in T.gens:
                        for S in basis:
                            sg, img = subset_action(T, r, S, g)
                            row = [0] * len(basis)
                            row[bi[img]] += sg
                            row[bi[S]] -= 1
                            rows.append(row)
                    ed = [e for e in matrix(ZZ, rows).elementary_divisors() if e]
                    free = len(basis) - len(ed)
                    tors = [e for e in ed if e != 1]
                    check(free == n_free and tors == [2] * n_two,
                          'cor:exterior-power-coinvariants: Lambda^%d((ZZ %s)^%d) (x)_B Z = '
                          'Z^%d + Z_2^%d (orbit sums Z^(eps) (x)_C ZZ B)'
                          % (k, name, r, n_free, n_two))
                check(n_two == 0 or (k % 2 == 0 and T.has_involution),
                      'cor:exterior-power-coinvariants: free if k odd or no element of order 2 '
                      '(%s, r = %d, k = %d)' % (name, r, k))


