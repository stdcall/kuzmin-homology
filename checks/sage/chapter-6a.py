class FreeAbelianExtension:
    """Phi = F/N' for B = F/N, F free on x_1..x_r, x_i -> images[i]."""

    def __init__(self, ords, images):
        B = self.B = AbGroup(ords)
        self.images = [tuple(b) for b in images]
        r = self.r = len(images)
        nB = B.order
        self.dimP = r * nB
        self.Pi = {}
        for h in B.elts:
            Pm = matrix(ZZ, self.dimP, self.dimP)
            for i in range(r):
                for g in B.elts:
                    Pm[i * nB + B.index[g], i * nB + B.index[B.mul(g, h)]] = 1
            self.Pi[h] = Pm
        S = matrix(ZZ, self.dimP, nB)
        for i in range(r):
            for g in B.elts:
                S[i * nB + B.index[g], B.index[B.mul(self.images[i], g)]] += 1
                S[i * nB + B.index[g], B.index[g]] -= 1
        self.sigma = S
        self.Mlat = S.left_kernel()
        self.Mb = self.Mlat.basis_matrix()
        self.d = self.Mb.nrows()
        self.A = {}
        for h in B.elts:
            rows = [self.Mlat.coordinate_vector(row * self.Pi[h])
                    for row in self.Mb.rows()]
            self.A[h] = matrix(ZZ, rows)
        self.Al = {h: [list(row) for row in self.A[h].rows()] for h in B.elts}
        self.word = {B.one: []}
        frontier = [B.one]
        while frontier:
            new = []
            for g in frontier:
                for i, b in enumerate(self.images):
                    h = B.mul(g, b)
                    if h not in self.word:
                        self.word[h] = self.word[g] + [i]
                        new.append(h)
            frontier = new
        assert len(self.word) == nB
        self.s = {}
        for g, w in self.word.items():
            el = (B.one, vector(ZZ, self.dimP))
            for i in w:
                el = self.wmul(el, self.gen(i))
            self.s[g] = el[1]
        self.cocycle = {}
        for g in B.elts:
            for h in B.elts:
                gh = B.mul(g, h)
                v = (self.s[g] * self.Pi[h] + self.s[h] - self.s[gh]) * self.Pi[B.inv(gh)]
                self.cocycle[(g, h)] = tuple(int(c) for c in self.Mlat.coordinate_vector(v))
        self.name = '%s, r = %d' % (B.name, r)

    one = property(lambda self: self.B.one)

    def resolution(self):
        return periodic_resolution(self.B)

    def gen(self, i):
        e = vector(ZZ, self.dimP)
        e[i * self.B.order + self.B.index[self.B.one]] = 1
        return (self.images[i], e)

    def wmul(self, x, y):
        (a, u), (b, v) = x, y
        return (self.B.mul(a, b), u * self.Pi[b] + v)

    def winv(self, x):
        a, u = x
        ai = self.B.inv(a)
        return (ai, -(u * self.Pi[ai]))

    def gmul(self, x, y):
        """(m, g)(m', h) = (m + m' g^-1 + c(g, h), g h), normal forms m s(g)."""
        (m1, g), (m2, h) = x, y
        A = self.Al[self.B.inv(g)]
        d = self.d
        t = [0] * d
        for i in range(d):
            if m2[i]:
                for j in range(d):
                    t[j] += m2[i] * A[i][j]
        c = self.cocycle[(g, h)]
        return (tuple(a + b + e for a, b, e in zip(m1, t, c)), self.B.mul(g, h))


class DerivedExtension:
    """1 -> Phi' -> Phi -> Z^r -> 1 (B abelian, so Phi' lies in M)."""

    def __init__(self, E):
        self.E = E
        B = E.B
        r = self.r = E.r
        vecs = []
        for i in range(r):
            for j in range(i + 1, r):
                xi, xj = E.gen(i), E.gen(j)
                c = E.wmul(E.wmul(E.winv(xi), E.winv(xj)), E.wmul(xi, xj))
                assert c[0] == B.one
                for h in B.elts:
                    vecs.append(c[1] * E.Pi[h])
        self.Nlat = (ZZ ** E.dimP).submodule(vecs)
        self.d = self.Nlat.rank()
        self.A = {}
        for h in B.elts:
            self.A[h] = [self.coords(row * E.Pi[h])
                         for row in self.Nlat.basis_matrix().rows()]
        self.sec = {}
        self.coc = {}

    one = property(lambda self: tuple(0 for _ in range(self.r)))

    def coords(self, v):
        c = self.Nlat.coordinate_vector(v)
        assert all(x in ZZ for x in c)
        return tuple(int(x) for x in c)

    def image(self, g):
        B = self.E.B
        out = B.one
        for i, a in enumerate(g):
            out = B.mul(out, B.power(self.E.images[i], a))
        return out

    def section(self, g):
        if g not in self.sec:
            E = self.E
            el = (E.B.one, vector(ZZ, E.dimP))
            for i, a in enumerate(g):
                x = E.gen(i) if a >= 0 else E.winv(E.gen(i))
                for _ in range(abs(a)):
                    el = E.wmul(el, x)
            self.sec[g] = el
        return self.sec[g]

    def cocycle(self, g, h):
        if (g, h) not in self.coc:
            E = self.E
            gh = tuple(a + b for a, b in zip(g, h))
            el = E.wmul(E.wmul(self.section(g), self.section(h)),
                        E.winv(self.section(gh)))
            assert el[0] == E.B.one
            self.coc[(g, h)] = self.coords(el[1])
        return self.coc[(g, h)]

    def gmul(self, x, y):
        (n1, g), (n2, h) = x, y
        A = self.A[self.E.B.inv(self.image(g))]
        d = self.d
        t = [0] * d
        for i in range(d):
            if n2[i]:
                for j in range(d):
                    t[j] += n2[i] * A[i][j]
        c = self.cocycle(g, h)
        return (tuple(a + b + e for a, b, e in zip(n1, t, c)),
                tuple(a + b for a, b in zip(g, h)))

    def resolution(self):
        r = self.r

        def basis(a):
            return list(itertools.combinations(range(r), a))

        def boundary(T):
            out = []
            for j, t in enumerate(T):
                sg = 1 if j % 2 == 0 else -1
                s = tuple(1 if i == t else 0 for i in range(r))
                out.append((T[:j] + T[j + 1:], {s: sg, self.one: -sg}))
            return out
        return basis, boundary, len


class WallResolution:
    """Free resolution of Phi from an extension 1 -> N -> Phi -> G -> 1 with
    N free abelian of rank d (Koszul complex K) and a free resolution F of G.
    Generators f (x) e_S; elements are dicts (f, S, n, g) -> coefficient,
    meaning f (x) e_S u^n (x) s(g).  D = d_0 + d_1 + ..., d_k(e) =
    -h(sum_(i=1)^(k-1) d_i d_(k-i) e + d_k d_0 e), h the contracting homotopy
    of K (x)_N ZZ Phi."""

    def __init__(self, E):
        self.E = E
        self.d = E.d
        self.basisF, self.boundF, self.fdeg = E.resolution()
        self.memo = {}
        self.zero = tuple(0 for _ in range(E.d))

    @staticmethod
    def clean(X):
        return {k: v for k, v in X.items() if v}

    def koszul(self, X):
        out = {}
        for (f, S, m, g), c in X.items():
            for j, s in enumerate(S):
                sg = c if j % 2 == 0 else -c
                S2 = S[:j] + S[j + 1:]
                k1 = (f, S2, m[:s] + (m[s] + 1,) + m[s + 1:], g)
                k0 = (f, S2, m, g)
                out[k1] = out.get(k1, 0) + sg
                out[k0] = out.get(k0, 0) - sg
        return self.clean(out)

    def homotopy(self, X):
        out = {}
        for (f, S, m, g), c in X.items():
            top = S[0] if S else self.d
            for i in range(top):
                mi = m[i]
                if mi:
                    S2 = (i,) + S
                    pre = (0,) * i
                    rest = m[i + 1:]
                    rng, sg = (range(0, mi), c) if mi > 0 else (range(mi, 0), -c)
                    for k in rng:
                        key = (f, S2, pre + (k,) + rest, g)
                        out[key] = out.get(key, 0) + sg
        return self.clean(out)

    def rmul(self, X, y):
        out = {}
        for (f, S, m, g), c in X.items():
            m2, g2 = self.E.gmul((m, g), y)
            key = (f, S, m2, g2)
            out[key] = out.get(key, 0) + c
        return self.clean(out)

    def apply(self, k, X):
        out = {}
        for (f, S, m, g), c in X.items():
            img = self.dk(k, f, S)
            if img:
                for key, v in self.rmul(img, (m, g)).items():
                    out[key] = out.get(key, 0) + c * v
        return self.clean(out)

    def dk(self, k, f, S):
        key = (k, f, S)
        if key in self.memo:
            return self.memo[key]
        a = self.fdeg(f)
        one = self.E.one
        if k == 0:
            res = self.koszul({(f, S, self.zero, one): 1})
        elif a - k < 0:
            res = {}
        elif k == 1 and not S:
            res = {}
            for f2, lam in self.boundF(f):
                for g, c in lam.items():
                    kk = (f2, (), self.zero, g)
                    res[kk] = res.get(kk, 0) + c
            res = self.clean(res)
        else:
            X = {}
            gen = {(f, S, self.zero, one): 1}
            for i in range(1, k):
                for kk, v in self.apply(i, self.apply(k - i, gen)).items():
                    X[kk] = X.get(kk, 0) + v
            if S:
                for kk, v in self.apply(k, self.koszul(gen)).items():
                    X[kk] = X.get(kk, 0) + v
            res = {kk: -v for kk, v in self.homotopy(self.clean(X)).items()}
        self.memo[key] = res
        return res

    def gens(self, n):
        return [(f, S) for a in range(n + 1) for f in self.basisF(a)
                for S in itertools.combinations(range(self.d), n - a)]

    def D(self, f, S):
        tot = {}
        for k in range(self.fdeg(f) + 1):
            for kk, v in self.dk(k, f, S).items():
                tot[kk] = tot.get(kk, 0) + v
        return self.clean(tot)

    def DD_zero(self, n):
        for f, S in self.gens(n):
            X = self.D(f, S)
            Y = {}
            for k in range(self.fdeg(f) + 1):
                for kk, v in self.apply(k, X).items():
                    Y[kk] = Y.get(kk, 0) + v
            if self.clean(Y):
                return False
        return True

    def matrix(self, n):
        rows, cols = self.gens(n), self.gens(n - 1)
        ci = {c: i for i, c in enumerate(cols)}
        Mx = matrix(ZZ, len(rows), len(cols), sparse=True)
        for i, (f, S) in enumerate(rows):
            for (f2, S2, m, g), v in self.D(f, S).items():
                Mx[i, ci[(f2, S2)]] += v
        return Mx


def homotopy_identity(W, trials):
    """d h + h d = 1 - eta eps on random elements of K (x)_N ZZ Phi."""
    f0 = W.basisF(0)[0]
    for _ in range(trials):
        S = tuple(sorted(random.sample(range(W.d), random.randint(0, min(3, W.d)))))
        m = tuple(random.randint(-3, 3) for _ in range(W.d))
        X = {(f0, S, m, W.E.one): 1}
        lhs = dict(W.koszul(W.homotopy(X)))
        for k, v in W.homotopy(W.koszul(X)).items():
            lhs[k] = lhs.get(k, 0) + v
        rhs = dict(X)
        if not S:
            key = (f0, (), W.zero, W.E.one)
            rhs[key] = rhs.get(key, 0) - 1
        if W.clean(lhs) != W.clean(rhs):
            return False
    return True


